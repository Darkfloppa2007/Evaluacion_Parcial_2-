import { useState } from "react";
function SolicitudesPanel({ solicitudes }) {
  const [busqueda, setBusqueda] = useState("");
  const [estado, setEstado] = useState("Todos");
  const [lista, setLista] = useState(solicitudes);
  const filtradas = lista.filter((solicitud) => {
    const nombreOk = solicitud.candidato.toLowerCase().includes(busqueda.toLowerCase());
    const estadoOk = 
    estado === "Todos" || solicitud.estado === estado;
    return nombreOk && estadoOk;
  });
  const siguienteEstado = {
    Pendiente: "En proceso",
    "En proceso": "Finalizada",
    Finalizada: "Finalizada"
  };
  const cambiarEstado = (id) => {
  
    setLista(  //2.2- setLista permite modificar el estado "lista".    
      lista.map((solicitud) =>
        solicitud.id === id
          ? { ...solicitud, estado: siguienteEstado[solicitud.estado] }
        
          : solicitud
      )
    );
  };
  






















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































  
  return (
  
    <section className="mt-5">
      <div className="d-flex flex-column flex-md-row justify-content-between gap-2 mb-3">
      
        <h2 className="h4">Solicitudes recientes</h2>
        
    {/* Mostramos cuántos elementos quedaron después de aplicar los filtros. */}
        <span>{filtradas.length} resultado(s)</span>
      </div>

      {/* 3. Inputs controlados por el estado de React. */}
      <div className="row g-2 mb-3">
        <div className="col-12 col-md-8">
        
          {/* Campo de texto utilizado para buscar candidatos. */}
          <input
            className="form-control"
            placeholder="Buscar candidato..."
            value={busqueda}
            onChange={(e) => setBusqueda(e.target.value)}
          />
          
        </div>
        
        

        <div className="col-12 col-md-4">
        
           {/* Select utilizado para filtrar por estado. */}
          <select
            className="form-select"
            value={estado}
            onChange={(e) => setEstado(e.target.value)}
          >
            <option value="Todos">Todos los estados</option>
            <option value="Pendiente">Pendiente</option>
            <option value="En proceso">En proceso</option>
            <option value="Finalizada">Finalizada</option>
          </select>
        </div>
      </div>

      {/* 4. Si no hay resultados mostramos un mensaje. */}
      {filtradas.length === 0 ? (
        <div className="alert alert-warning">
          No se encontraron solicitudes.
        </div>
        
         

      ) : (
        <div className="table-responsive">
          <table className="table table-hover align-middle">
            <thead>
              <tr>
                <th>Candidato</th>
                <th>Cargo</th>
                <th>Estado</th>
                <th>Acción</th>
              </tr>
            </thead>

            <tbody>
            
      {/* Recorremos las solicitudes filtradas utilizando map(). */}
              {filtradas.map((solicitud) => (
            
                <tr key={solicitud.id}>
                  <td>{solicitud.candidato}</td>
                  <td>{solicitud.cargo}</td>
                  <td>{solicitud.estado}</td>

                  <td>
                    {solicitud.estado !== "Finalizada" && (
                      <button className="btn btn-sm btn-outline-primary"
                        onClick={() => cambiarEstado(solicitud.id)}>
                        Avanzar estado
                      </button>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </section>
  );
}

export default SolicitudesPanel;